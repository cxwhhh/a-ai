/**
 * 内置技能：写在代码里、所有用户都有的技能。
 *
 * 和学会的技能（server/skills.ts，从用户以往的任务里总结）用法完全一样：
 * 系统提示词的技能目录里有一行“名字：什么时候用”，任务对得上时模型调用 load_skill 读全文。
 * 区别是：内置技能不存数据库、不统计成功率、不会被自动改写或停用；用户学会的技能和它同名时，以用户的为准。
 *
 * 什么适合写成内置技能：做好一类任务需要的“知识和规范”（怎么设计、注意什么），
 * 而不是“能力”（能力写成工具）。例：网页怎么设计得好看是知识；自动套样式、检查页面是能力（见 tools/html-polish.ts）。
 */
